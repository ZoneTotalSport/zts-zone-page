let cur = 'fr';

export function initLang() {
  try { cur = localStorage.getItem('zts-studio-lang') || 'fr'; } catch (_) {}
  if (!T[cur]) cur = 'fr';
  document.body.dataset.lang = cur;
  return cur;
}
export function lang() { return cur; }
export function setLang(l) {
  if (!T[l]) return;
  cur = l;
  try { localStorage.setItem('zts-studio-lang', l); } catch (_) {}
  document.body.dataset.lang = l;
}
export function t(k) {
  const v = T[cur][k];
  return v != null ? v : (T.fr[k] != null ? T.fr[k] : k);
}
/** Applique la langue aux textes statiques du HTML (data-i18n*). */
export function applyStatic() {
  document.querySelectorAll('[data-i18n]').forEach((e) => { e.textContent = t(e.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach((e) => { e.title = t(e.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-ph]').forEach((e) => {
    const v = t(e.dataset.i18nPh);
    if ('placeholder' in e) e.placeholder = v;
    e.setAttribute('data-ph', v); // placeholder CSS des divs contenteditable
  });
  document.querySelectorAll('[data-i18n-html]').forEach((e) => { e.innerHTML = t(e.dataset.i18nHtml); });
}
